import PDFDocument from 'pdfkit';

export interface PDFReportData {
  title: string;
  subtitle: string;
  generatedBy: string;
  generatedAt: string;
  dateRange: string;
  metrics: Array<{ label: string; value: string | number; change?: string }>;
  tables: Array<{
    title: string;
    headers: string[];
    rows: (string | number)[][];
  }>;
}

/**
 * Generates a PDF operational report buffer using PDFKit
 */
export async function generateOperationalPdfReport(data: PDFReportData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'A4',
      margin: 40,
      info: {
        Title: data.title,
        Author: 'Accommodation Management System',
        Subject: 'Operational & Occupancy Report',
      },
    });

    const buffers: Buffer[] = [];
    doc.on('data', (chunk) => buffers.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(buffers)));
    doc.on('error', (err) => reject(err));

    const navyBlue = '#0f172a';
    const primaryBlue = '#2563eb';
    const slateGray = '#64748b';
    const borderGray = '#e2e8f0';

    // ------------------------------------------------------------------------
    // HEADER BAR
    // ------------------------------------------------------------------------
    doc.rect(40, 40, 515, 60).fill(navyBlue);

    doc.fillColor('#ffffff').fontSize(16).font('Helvetica-Bold')
      .text('ACCOMMODATION MANAGEMENT SYSTEM', 55, 52);
    
    doc.fillColor('#94a3b8').fontSize(9).font('Helvetica')
      .text('OFFICIAL ADMINISTRATIVE & OPERATIONAL AUDIT REPORT', 55, 74);

    doc.fillColor('#ffffff').fontSize(8).font('Helvetica-Bold')
      .text(`DATE RANGE: ${data.dateRange}`, 370, 74, { align: 'right', width: 170 });

    doc.y = 115;

    // ------------------------------------------------------------------------
    // REPORT TITLE & METADATA
    // ------------------------------------------------------------------------
    doc.fillColor(navyBlue).fontSize(14).font('Helvetica-Bold')
      .text(data.title, 40, 115);

    doc.fillColor(slateGray).fontSize(9).font('Helvetica')
      .text(data.subtitle, 40, 133);

    doc.fontSize(8).font('Helvetica')
      .text(`Generated By: ${data.generatedBy}   |   Timestamp: ${data.generatedAt}`, 40, 148);

    doc.moveTo(40, 162).lineTo(555, 162).strokeColor(borderGray).lineWidth(1).stroke();

    // ------------------------------------------------------------------------
    // KPI METRICS GRID
    // ------------------------------------------------------------------------
    let currentY = 175;
    doc.fillColor(navyBlue).fontSize(11).font('Helvetica-Bold')
      .text('EXECUTIVE OPERATIONAL HIGHLIGHTS', 40, currentY);

    currentY += 18;
    const cardWidth = 120;
    const cardHeight = 46;
    const gap = 11;

    data.metrics.slice(0, 4).forEach((metric, index) => {
      const cardX = 40 + index * (cardWidth + gap);
      
      // Card container
      doc.roundedRect(cardX, currentY, cardWidth, cardHeight, 4)
        .fillAndStroke('#f8fafc', borderGray);

      // Card Metric Value
      doc.fillColor(primaryBlue).fontSize(14).font('Helvetica-Bold')
        .text(String(metric.value), cardX + 8, currentY + 8);

      // Card Label
      doc.fillColor(slateGray).fontSize(7.5).font('Helvetica-Bold')
        .text(metric.label.toUpperCase(), cardX + 8, currentY + 28, { width: cardWidth - 16 });
    });

    currentY += cardHeight + 25;

    // ------------------------------------------------------------------------
    // TABLES SECTION
    // ------------------------------------------------------------------------
    for (const table of data.tables) {
      // Check if page overflow
      if (currentY > 660) {
        doc.addPage();
        currentY = 40;
      }

      doc.fillColor(navyBlue).fontSize(11).font('Helvetica-Bold')
        .text(table.title.toUpperCase(), 40, currentY);

      currentY += 16;

      const colCount = table.headers.length;
      const colWidth = 515 / colCount;

      // Table Header Row
      doc.rect(40, currentY, 515, 20).fill('#f1f5f9');
      table.headers.forEach((header, i) => {
        doc.fillColor(navyBlue).fontSize(8).font('Helvetica-Bold')
          .text(header, 44 + i * colWidth, currentY + 6, {
            width: colWidth - 8,
            align: i === colCount - 1 ? 'right' : 'left',
          });
      });

      currentY += 20;

      // Table Rows
      table.rows.forEach((row, rowIndex) => {
        if (currentY > 740) {
          doc.addPage();
          currentY = 40;
        }

        const isAlt = rowIndex % 2 === 1;
        if (isAlt) {
          doc.rect(40, currentY, 515, 18).fill('#f8fafc');
        }

        row.forEach((cell, i) => {
          doc.fillColor('#1e293b').fontSize(8).font('Helvetica')
            .text(String(cell), 44 + i * colWidth, currentY + 5, {
              width: colWidth - 8,
              align: i === colCount - 1 ? 'right' : 'left',
            });
        });

        currentY += 18;
      });

      currentY += 18;
    }

    // ------------------------------------------------------------------------
    // FOOTER NOTICE
    // ------------------------------------------------------------------------
    const pageCount = (doc as any)._pageBuffer?.length || 1;
    doc.fillColor('#94a3b8').fontSize(7.5).font('Helvetica')
      .text(
        'CONFIDENTIAL & PRIVILEGED: Contains internal accommodation operations data. Strictly zero Aadhaar numbers are stored or rendered. Accommodation Management System © 2026',
        40,
        780,
        { align: 'center', width: 515 }
      );

    doc.end();
  });
}
